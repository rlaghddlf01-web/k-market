// 4. 언어별 번역 함수 (순수 고유어 치환 + 완전 대체)
function translateKey(krText, lang) {
  if (!krText) return '';
  let text = krText;

  const vocab = PURE_LANG_TERMS[lang] || PURE_LANG_TERMS.zh;

  for (const [kr, localized] of Object.entries(vocab)) {
    if (text.includes(kr)) {
      text = text.split(kr).join(localized);
    }
  }

  return text;
}

