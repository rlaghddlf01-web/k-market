// 16개 언어 파일 전수 생성
const localesDir = path.join(__dirname, '..', 'src', 'lib', 'i18n', 'locales');

for (const lang of ALL_LANGS) {
  const filePath = path.join(localesDir, `${lang}.ts`);
  const specificMap = TRANSLATION_MAPS[lang] || {};
  const enMap = TRANSLATION_MAPS.en || {};

  let fileContent = `import { TranslationDictionary } from '../types';\n\nexport const ${lang}: TranslationDictionary = {\n`;

  for (const [key, koVal] of Object.entries(koEntries)) {
    // 1순위: 해당 언어 번역값, 2순위: 영어 번역값, 3순위: 한국어
    const val = specificMap[key] || enMap[key] || koVal;
    fileContent += `  ${key}: ${JSON.stringify(val)},\n`;
  }

  fileContent += `};\n`;
  fs.writeFileSync(filePath, fileContent, 'utf8');
  console.log(`✅ [${lang.toUpperCase()}] 216개 전수 키 1:1 완벽 대칭 사전 생성 완료`);
}
