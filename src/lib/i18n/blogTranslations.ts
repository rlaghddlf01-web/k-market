/**
 * 17개국어 블로그 전용 UI 문자열 안전 변환 헬퍼
 */
export function getBlogTranslation(key: string, lang: string = 'ko'): string {
  const normLang = (lang || 'ko').toLowerCase();
  const dict = BLOG_TRANSLATIONS[key];
  if (!dict) return key;
  return dict[normLang] || dict['ko'] || dict['en'] || key;
}
